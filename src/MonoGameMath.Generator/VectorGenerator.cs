using System;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace MonoGameMath.Generator;

[Generator]
public sealed class VectorGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var definitions = context.CompilationProvider.Select(static (_, _) => VectorDefinitions.All);
        context.RegisterSourceOutput(definitions, EmitSkeletons);
    }

    private static void EmitSkeletons(SourceProductionContext context, VectorDefinitionSet definitions)
    {
        foreach (var numeric in definitions.Numerics)
        {
            foreach (var vector in definitions.Vectors)
            {
                var typeName = vector.Name + numeric.NameSuffix;
                context.AddSource(typeName + ".g.cs", SourceText.From(BuildSkeleton(typeName, vector, numeric), Encoding.UTF8));
            }
        }
    }

    private static string BuildSkeleton(string typeName, VectorDefinition vector, NumericVariant numeric)
    {
        var source = new StringBuilder();

        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace MonoGameMath;");
        source.AppendLine();
        source.AppendLine($"public partial struct {typeName} : IEquatable<{typeName}>");
        source.AppendLine("{");

        foreach (var component in vector.Components)
        {
            source.AppendLine($"    public {numeric.Keyword} {component};");
        }

        source.AppendLine();

        var parameters = string.Join(
            ", ",
            vector.Components.Select(component => $"{numeric.Keyword} {component.ToLowerInvariant()}"));

        source.AppendLine($"    public {typeName}({parameters})");
        source.AppendLine("    {");

        foreach (var component in vector.Components)
        {
            source.AppendLine($"        {component} = {component.ToLowerInvariant()};");
        }

        source.AppendLine("    }");
        source.AppendLine();

        source.AppendLine($"    public static readonly {typeName} Zero = new {typeName}({ComponentValues(vector, numeric, _ => false)});");
        source.AppendLine($"    public static readonly {typeName} One = new {typeName}({ComponentValues(vector, numeric, _ => true)});");

        foreach (var unit in vector.Components)
        {
            source.AppendLine($"    public static readonly {typeName} Unit{unit} = new {typeName}({ComponentValues(vector, numeric, component => component == unit)});");
        }

        source.AppendLine();

        EmitArithmeticOperators(source, typeName, vector, numeric);
        EmitCopyReturningOperations(source, typeName, vector);
        EmitInPlaceOperations(source, typeName, vector);

        var equalsBody = string.Join(" && ", vector.Components.Select(component => $"{component} == other.{component}"));

        source.AppendLine($"    public bool Equals({typeName} other)");
        source.AppendLine("    {");
        source.AppendLine($"        return {equalsBody};");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine("    public override bool Equals(object? obj)");
        source.AppendLine("    {");
        source.AppendLine($"        return obj is {typeName} other && Equals(other);");
        source.AppendLine("    }");
        source.AppendLine();

        var hashBody = string.Join(" ^ ", vector.Components.Select(component => $"{component}.GetHashCode()"));

        source.AppendLine("    public override int GetHashCode()");
        source.AppendLine("    {");
        source.AppendLine($"        return {hashBody};");
        source.AppendLine("    }");
        source.AppendLine();

        var componentsText = string.Join(" ", vector.Components.Select(component => $"{component}:{{{component}}}"));

        source.AppendLine("    public override string ToString()");
        source.AppendLine("    {");
        source.AppendLine("        return $\"{{" + componentsText + "}}\";");
        source.AppendLine("    }");
        source.AppendLine();

        source.AppendLine($"    public static bool operator ==({typeName} left, {typeName} right)");
        source.AppendLine("    {");
        source.AppendLine("        return left.Equals(right);");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine($"    public static bool operator !=({typeName} left, {typeName} right)");
        source.AppendLine("    {");
        source.AppendLine("        return !left.Equals(right);");
        source.AppendLine("    }");
        source.AppendLine("}");

        return source.ToString();
    }

    private static void EmitArithmeticOperators(StringBuilder source, string typeName, VectorDefinition vector, NumericVariant numeric)
    {
        EmitBinaryOperator(source, typeName, vector, "+");
        EmitBinaryOperator(source, typeName, vector, "-");

        source.AppendLine($"    public static {typeName} operator -({typeName} value)");
        source.AppendLine("    {");
        source.AppendLine($"        return new {typeName}({ComponentExpressions(vector, component => $"-value.{component}")});");
        source.AppendLine("    }");
        source.AppendLine();

        source.AppendLine($"    public static {typeName} operator *({typeName} value, {numeric.Keyword} scalar)");
        source.AppendLine("    {");
        source.AppendLine($"        return new {typeName}({ComponentExpressions(vector, component => $"value.{component} * scalar")});");
        source.AppendLine("    }");
        source.AppendLine();
        source.AppendLine($"    public static {typeName} operator *({numeric.Keyword} scalar, {typeName} value)");
        source.AppendLine("    {");
        source.AppendLine($"        return new {typeName}({ComponentExpressions(vector, component => $"scalar * value.{component}")});");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void EmitBinaryOperator(StringBuilder source, string typeName, VectorDefinition vector, string symbol)
    {
        source.AppendLine($"    public static {typeName} operator {symbol}({typeName} left, {typeName} right)");
        source.AppendLine("    {");
        source.AppendLine($"        return new {typeName}({ComponentExpressions(vector, component => $"left.{component} {symbol} right.{component}")});");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void EmitCopyReturningOperations(StringBuilder source, string typeName, VectorDefinition vector)
    {
        EmitStaticOperation(source, typeName, vector, "Add", "+");
        EmitStaticOperation(source, typeName, vector, "Subtract", "-");
    }

    private static void EmitStaticOperation(StringBuilder source, string typeName, VectorDefinition vector, string name, string symbol)
    {
        source.AppendLine($"    public static {typeName} {name}({typeName} left, {typeName} right)");
        source.AppendLine("    {");
        source.AppendLine($"        return new {typeName}({ComponentExpressions(vector, component => $"left.{component} {symbol} right.{component}")});");
        source.AppendLine("    }");
        source.AppendLine();
    }

    private static void EmitInPlaceOperations(StringBuilder source, string typeName, VectorDefinition vector)
    {
        EmitInPlaceOperation(source, typeName, vector, "Add", "+=");
        EmitInPlaceOperation(source, typeName, vector, "Subtract", "-=");
    }

    private static void EmitInPlaceOperation(StringBuilder source, string typeName, VectorDefinition vector, string name, string assignment)
    {
        source.AppendLine($"    public void {name}({typeName} other)");
        source.AppendLine("    {");

        foreach (var component in vector.Components)
        {
            source.AppendLine($"        {component} {assignment} other.{component};");
        }

        source.AppendLine("    }");
        source.AppendLine();
    }

    private static string ComponentExpressions(VectorDefinition vector, Func<string, string> expression)
    {
        return string.Join(", ", vector.Components.Select(expression));
    }

    private static string ComponentValues(VectorDefinition vector, NumericVariant numeric, Func<string, bool> isOne)
    {
        return string.Join(", ", vector.Components.Select(component => (isOne(component) ? "1" : "0") + numeric.LiteralSuffix));
    }
}
